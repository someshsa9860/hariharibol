// The prayers we want, where each one's original text is taken from, and what we know about it. Read by
// scripts/fetch-prayers.js, which fetches the texts into public/prayers/json/ and writes public/prayers/PRAYERS.md
// from this list, so the list and the files cannot drift apart.
//
// One entry per prayer:
//
//   slug, title (English, with diacritics), titleOriginal (in the original's own script)
//   category        one of config/prayer.js CATEGORIES (morning, evening, meals, guru, deity, aarti, peace, other)
//   sortOrder       lists are shown in this order within a category
//   originalLanguage  a config/prayer.js ORIGINAL_LANGUAGES code; a kksongs.org entry may leave it to the page
//   tradition       vaishnava | shaiva | shakta | ganapatya | dattatreya | smarta (shared by every tradition)
//   deity           who it is addressed to (krishna, gaura, radha, guru, tulasi, narasimha, jagannatha, shiva …)
//   occasions       when it is said, in a few words each
//   festivals       festival slugs from services/festivals.js the app can surface it on
//   summary, about  our own words, never a source's
//   author, reference  as printed by tradition; checked against the source page where it names them
//   authorWhy       why our author differs from the page's (the page names the book's author, not the speaker's)
//   source          where the original text comes from (see fetch-prayers.js for the kinds)
//   join            { verses: [1, 2], why }: verses one copy splits and another keeps as one, made one verse
//   edits           corrections to the source text, each with a reason; a correction whose `from` is not found stops
//                   the run, so a source that fixes itself is noticed. `field` is 'text' (the original script) or
//                   'roman'; `verse` counts as on the page, after `join`
//   select          { verses: [1], why }: only these verses are the prayer (the page holds more)
//   status          fetch | gap (wanted, no usable free source found yet) | excluded (not to be published)
//   note            why, for a gap or an exclusion
//
// Meanings are left empty on purpose: the English translations on these sites are modern and under copyright (the
// BBT's on kksongs.org). The originals are centuries old.

